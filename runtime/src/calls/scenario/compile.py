"""Build step: ``.flow`` → validated → Python switch-case module + Mermaid diagram.

    python -m calls.scenario.compile scenarios/ -o src/calls/scenario/compiled --mermaid docs/flows
    python -m calls.scenario.compile scenarios/ -o src/calls/scenario/compiled --check   # CI freshness

The generated module contains the transition table as literal ``match``
statements (``dispatch(state, kind, value)``), the prompts and the statement
list, plus the SHA-256 of the source so a stale artefact is detected.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path
from typing import Optional

from .dsl import Flow, FlowError, load_flows, validate

HEADER = "# Generated by calls.scenario.compile from {src} — DO NOT EDIT (run `make scenarios`).\n"


def _lit(v: object) -> str:
    return repr(v)


def generate_python(flow: Flow, source_text: str) -> str:
    sha = hashlib.sha256(source_text.encode("utf-8")).hexdigest()
    out: list[str] = [HEADER.format(src=Path(flow.source).name), "from __future__ import annotations\n", ""]
    out.append(f"FLOW_NAME = {_lit(flow.name)}")
    out.append(f"ENTRY = {_lit(flow.entry)}")
    out.append(f"OPTIONS = {_lit(dict(flow.options))}")
    out.append(f"SOURCE_SHA256 = {_lit(sha)}")
    out.append("")
    out.append("# state → list of statements (kind, args, text)")
    out.append("STATEMENTS: dict[str, list[tuple[str, dict[str, str], str]]] = {")
    for name, st in flow.states.items():
        out.append(f"    {_lit(name)}: [")
        for s in st.statements:
            out.append(f"        ({_lit(s.kind)}, {_lit(dict(s.args))}, {_lit(s.text)}),")
        out.append("    ],")
    out.append("}")
    out.append("")
    out.append("# state → list of edges (kind, values, target, sets, seconds, count)")
    out.append("EDGES: dict[str, list[tuple[str, tuple[str, ...], str, dict[str, str], float | None, int | None]]] = {")
    for name, st in flow.states.items():
        out.append(f"    {_lit(name)}: [")
        for e in st.edges:
            out.append(f"        ({_lit(e.kind)}, {_lit(tuple(e.values))}, {_lit(e.target)}, {_lit(dict(e.sets))}, {_lit(e.seconds)}, {_lit(e.count)}),")
        out.append("    ],")
    out.append("}")
    out.append("")
    out.append("")
    out.append("def dispatch(state: str, kind: str, value: str = \"\") -> str | None:")
    out.append('    """Switch-case transition table: target state for (state, event kind, value) or None."""')
    out.append("    match state:")
    for name, st in flow.states.items():
        out.append(f"        case {_lit(name)}:")
        if not st.edges:
            out.append("            return None")
            continue
        out.append("            match (kind, value):")
        for e in st.edges:
            if e.values:
                pats = " | ".join(f"({_lit(e.kind)}, {_lit(v)})" for v in e.values)
            else:
                pats = f"({_lit(e.kind)}, _)"
            out.append(f"                case {pats}:")
            out.append(f"                    return {_lit(e.target)}")
        out.append("                case _:")
        out.append("                    return None")
    out.append("        case _:")
    out.append("            return None")
    out.append("")
    return "\n".join(out)


def generate_mermaid(flow: Flow) -> str:
    lines = ["flowchart TD"]

    def node(name: str) -> str:
        st = flow.states[name]
        kinds = {s.kind for s in st.statements}
        label = name
        if "transfer" in kinds:
            return f'{name}{{{{"{label}\\nоператор"}}}}'
        if "end" in kinds:
            return f'{name}(("{label}"))'
        if "call" in kinds:
            call = next(s for s in st.statements if s.kind == "call")
            return f'{name}[["{label}\\n{call.args["module"]}.{call.args["op"]}"]]'
        if "ask" in kinds:
            return f'{name}[/"{label}\\nDTMF ввод"/]'
        if st.listens:
            return f'{name}["{label}\\nASR"]'
        return f'{name}["{label}"]'

    for name in flow.states:
        lines.append("    " + node(name))
    for name, st in flow.states.items():
        for e in st.edges:
            label = e.label.replace('"', "'")
            if e.sets:
                label += " " + " ".join(f"{k}={v}" for k, v in e.sets.items())
            tgt = e.target.replace(".", "_")
            lines.append(f'    {name} -->|"{label}"| {tgt}')
        for s in st.statements:
            if s.kind == "goto":
                lines.append(f"    {name} --> {s.args['target'].replace('.', '_')}")
            if s.kind == "enter":
                lines.append(f'    {name} -.->|"enter"| {s.args["target"].replace(".", "_")}')
                lines.append(f'    {s.args["target"].replace(".", "_")} -.->|"return"| {s.args["return"]}')
    lines.append("    classDef entry fill:#dfd,stroke:#393;")
    lines.append(f"    class {flow.entry} entry;")
    return "\n".join(lines) + "\n"


def build(src_dir: Path, out_dir: Optional[Path], mermaid_dir: Optional[Path], check: bool) -> int:
    flows = load_flows(src_dir)
    if not flows:
        print(f"no .flow files in {src_dir}", file=sys.stderr)
        return 2
    problems = validate(flows)
    if problems:
        for p in problems:
            print(p, file=sys.stderr)
        print(f"{len(problems)} problem(s) in scenarios", file=sys.stderr)
        return 1
    stale: list[str] = []
    if out_dir is not None:
        if not check:
            out_dir.mkdir(parents=True, exist_ok=True)
            (out_dir / "__init__.py").write_text(
                "# Generated package: compiled scenarios. DO NOT EDIT.\n"
                f"FLOWS = {sorted(flows)!r}\n",
                encoding="utf-8",
            )
        for name, flow in flows.items():
            text = generate_python(flow, Path(flow.source).read_text(encoding="utf-8"))
            target = out_dir / f"{name}.py"
            if check:
                if not target.exists() or target.read_text(encoding="utf-8") != text:
                    stale.append(str(target))
            else:
                target.write_text(text, encoding="utf-8")
    if mermaid_dir is not None:
        for name, flow in flows.items():
            text = generate_mermaid(flow)
            target = mermaid_dir / f"{name}.mmd"
            if check:
                if not target.exists() or target.read_text(encoding="utf-8") != text:
                    stale.append(str(target))
            else:
                mermaid_dir.mkdir(parents=True, exist_ok=True)
                target.write_text(text, encoding="utf-8")
    if stale:
        print("stale compiled scenarios (run `python -m calls.scenario.compile`):", file=sys.stderr)
        for s in stale:
            print("  " + s, file=sys.stderr)
        return 1
    if not check:
        print(f"compiled {len(flows)} flow(s): {', '.join(flows)}")
    return 0


def main(argv: Optional[list[str]] = None) -> int:
    ap = argparse.ArgumentParser(description="Compile .flow scenarios")
    ap.add_argument("src", nargs="?", default="scenarios", help="directory with .flow files")
    ap.add_argument("-o", "--out", default="src/calls/scenario/compiled", help="output package dir ('' to skip)")
    ap.add_argument("--mermaid", default="docs/flows", help="directory for .mmd diagrams ('' to skip)")
    ap.add_argument("--check", action="store_true", help="fail if generated files are stale")
    ns = ap.parse_args(argv)
    try:
        return build(Path(ns.src), Path(ns.out) if ns.out else None, Path(ns.mermaid) if ns.mermaid else None, ns.check)
    except FlowError as exc:
        print(str(exc), file=sys.stderr)
        return 1


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
