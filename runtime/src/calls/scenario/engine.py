"""Scenario engine: a deterministic state machine driven by events.

The engine never touches the clock, the network or audio – it turns
``Event`` objects into ``Action`` objects, so a whole call can be replayed in a
unit test in microseconds.  The orchestrator (``calls.orchestrator.session``)
executes actions (TTS, DTMF collection, module calls) and feeds the results
back as events.

Hot path = :meth:`Session.handle`.  Transition lookup is a dictionary switch
built from the flow (``_Table``); the compiled module generated by
``calls.scenario.compile`` contains the same table as literal ``match``
statements for environments where the ``.flow`` files are not shipped.
"""

from __future__ import annotations

import itertools
import re
from dataclasses import dataclass, field
from datetime import date
from typing import Callable, Optional

from calls.nlu.intent import IntentResult, classify
from calls.nlu.normalize import Interpretation, interpret

from .dsl import Edge, Flow, State

_PLACEHOLDER_RE = re.compile(r"\{([a-zA-Z_][a-zA-Z0-9_]*)\}")
DAYPART_SPOKEN = {"morning": "утром", "midday": "в обед", "afternoon": "после обеда", "evening": "вечером"}


# --------------------------------------------------------------------------------------
# Events & actions
# --------------------------------------------------------------------------------------


@dataclass
class Event:
    kind: str  # dtmf | speech | silence | timeout | module | hangup
    value: str = ""  # digit / recognised text / module status
    payload: dict = field(default_factory=dict)
    request_id: Optional[int] = None  # for module results


@dataclass
class Action:
    kind: str  # say | collect | listen | timer | call | transfer | sms | end | stop_playback
    text: str = ""
    rate: float = 1.0
    args: dict = field(default_factory=dict)
    request_id: Optional[int] = None

    def __repr__(self) -> str:  # compact for test diffs
        extra = f" {self.args}" if self.args else ""
        txt = f" {self.text!r}" if self.text else ""
        return f"<{self.kind}{txt}{extra}>"


@dataclass
class NluOutcome:
    interpretation: Interpretation
    intent: IntentResult


NluFn = Callable[[str, date], NluOutcome]


def default_nlu(text: str, today: date) -> NluOutcome:
    return NluOutcome(interpret(text, today), classify(text, today))


# --------------------------------------------------------------------------------------
# Session
# --------------------------------------------------------------------------------------


@dataclass
class _Pending:
    request_id: int
    module: str
    op: str


class Session:
    """One call = one Session.  Not thread-safe by design: the orchestrator owns it."""

    _ids = itertools.count(1)

    def __init__(
        self,
        flows: dict[str, Flow],
        flow: str,
        vars: Optional[dict] = None,
        today: Optional[date] = None,
        nlu: NluFn = default_nlu,
        intent_threshold: float = 0.6,
    ) -> None:
        if flow not in flows:
            raise KeyError(f"unknown flow {flow!r}")
        self.flows = flows
        self.flow = flows[flow]
        self.vars: dict = dict(vars or {})
        self.today = today or date.today()
        self.nlu = nlu
        self.intent_threshold = intent_threshold
        self.state: Optional[State] = None
        self.stack: list[tuple[str, str]] = []  # (flow, return_state)
        self.retries: dict[str, int] = {}
        self.visits: dict[str, int] = {}
        self.history: list[str] = []
        self.warnings: list[str] = []
        self.finished = False
        self.status: Optional[str] = None
        self.transfer: Optional[dict] = None
        self.sms_sent: list[dict] = []
        self._digits = ""
        self._ask: Optional[dict] = None
        self._pending: Optional[_Pending] = None
        self._awaiting_input = False

    # ---- public API ---------------------------------------------------------------

    @property
    def state_name(self) -> str:
        return f"{self.flow.name}.{self.state.name}" if self.state else ""

    def start(self) -> list[Action]:
        return self._enter(self.flow.entry, from_state=None)

    def handle(self, event: Event) -> list[Action]:
        if self.finished or self.state is None:
            return []
        if event.kind == "hangup":
            self.finished, self.status = True, "hangup"
            return [Action("end", args={"status": "hangup"})]
        if event.kind == "module":
            return self._on_module(event)
        if self._pending is not None:
            # user input while a module call is in flight: ignore (the prompt said "подождите")
            return []
        if event.kind == "dtmf":
            return self._on_dtmf(event.value)
        if event.kind == "speech":
            return self._on_speech(event.value)
        if event.kind == "silence":
            e = self.state.edge("silence")
            if e is not None:
                return self._follow(e)
            return self._on_timeout()
        if event.kind == "timeout":
            return self._on_timeout()
        self.warnings.append(f"unknown event {event.kind}")
        return []

    # ---- state entry --------------------------------------------------------------

    def _lookup(self, ref: str) -> tuple[Flow, State]:
        if "." in ref:
            fname, sname = ref.split(".", 1)
            flow = self.flows[fname]
        else:
            flow, sname = self.flow, ref
        return flow, flow.states[sname]

    def _enter(self, ref: str, from_state: Optional[str]) -> list[Action]:
        flow, state = self._lookup(ref)
        if from_state != state.name:
            self.retries[state.name] = 0
        self.flow, self.state = flow, state
        self.visits[state.name] = self.visits.get(state.name, 0) + 1
        self.history.append(self.state_name)
        if len(self.history) > 500:  # runaway loop guard
            self.finished, self.status = True, "loop_guard"
            return [Action("end", args={"status": "loop_guard"})]
        loop_edge = state.edge("loop")
        if loop_edge is not None and loop_edge.count is not None and self.visits[state.name] > loop_edge.count:
            return self._follow(loop_edge)
        self._digits, self._ask, self._pending, self._awaiting_input = "", None, None, False
        actions: list[Action] = []
        for st in state.statements:
            k = st.kind
            if k == "set":
                self.vars[st.args["var"]] = self._value(st.args["value"])
                if st.args["var"] == "said_daypart" and self.vars["said_daypart"] in DAYPART_SPOKEN:
                    self.vars["said_daypart_spoken"] = DAYPART_SPOKEN[self.vars["said_daypart"]]
            elif k == "say":
                rate = float(st.args.get("rate", flow.options.get("rate", "1.0")))
                actions.append(Action("say", self._render(st.text), rate))
            elif k == "sms":
                sms = {"template": st.args["template"], "vars": dict(self.vars)}
                self.sms_sent.append(sms)
                actions.append(Action("sms", args=sms))
            elif k == "transfer":
                reason = self._value(st.args.get("reason", "$reason")) or "unspecified"
                self.transfer = {"reason": reason, "vars": dict(self.vars), "history": list(self.history)}
                actions.append(Action("transfer", args=self.transfer))
            elif k == "call":
                rid = next(Session._ids)
                args = {key[4:]: self._value(v) for key, v in st.args.items() if key.startswith("arg:")}
                self._pending = _Pending(rid, st.args["module"], st.args["op"])
                actions.append(Action("call", args={"module": st.args["module"], "op": st.args["op"], "args": args}, request_id=rid))
            elif k == "ask":
                self._ask = dict(st.args)
                self._awaiting_input = True
                actions.append(Action("collect", args={"var": st.args["var"], "min": int(st.args["min"]), "max": int(st.args["max"]), "terminator": st.args.get("terminator", "#")}))
                actions.append(Action("timer", args={"seconds": float(st.args.get("timeout", "15"))}))
            elif k == "listen":
                self._awaiting_input = True
                actions.append(Action("listen", args={"seconds": float(st.args["timeout"])}))
            elif k == "end":
                self.finished, self.status = True, st.args["status"]
                actions.append(Action("end", args={"status": st.args["status"]}))
                return actions
            elif k == "goto":
                return actions + self._enter(st.args["target"], state.name)
            elif k == "enter":
                self.stack.append((flow.name, st.args["return"]))
                return actions + self._enter(st.args["target"], state.name)
            elif k == "switch":
                val = self.vars.get(st.args["var"])
                sval = "none" if val in (None, "") else str(val).lower()
                chosen = next((e for e in state.edges if e.kind == "case" and e.values[0].lower() == sval), None) or state.edge("default")
                assert chosen is not None  # validator guarantees a default
                return actions + self._follow(chosen)
            elif k == "return":
                if not self.stack:
                    self.finished, self.status = True, "error"
                    self.warnings.append("return with empty stack")
                    return actions + [Action("end", args={"status": "error"})]
                fname, back = self.stack.pop()
                self.flow = self.flows[fname]
                return actions + self._enter(back, state.name)
        if self._pending is None and state.edges and not self._ask and not any(a.kind in ("listen",) for a in actions):
            # a menu / yes-no state: arm the timer from the timeout edge (default 10 s)
            if state.waits_for_input:
                self._awaiting_input = True
                t = state.edge("timeout")
                actions.append(Action("timer", args={"seconds": t.seconds if t and t.seconds else 10.0}))
                if state.listens:
                    actions.append(Action("listen", args={"seconds": t.seconds if t and t.seconds else 10.0}))
        return actions

    # ---- event handlers -----------------------------------------------------------

    def _on_dtmf(self, digit: str) -> list[Action]:
        assert self.state is not None
        if self._ask is not None:
            if digit == "*":
                self._digits = ""
                return [Action("stop_playback")]
            term = self._ask.get("terminator", "#")
            mn, mx = int(self._ask["min"]), int(self._ask["max"])
            if digit == term:
                if len(self._digits) >= mn:
                    return self._ask_done()
                return self._invalid()
            if digit.isdigit():
                self._digits += digit
                if len(self._digits) >= mx:
                    return self._ask_done()
            return [Action("stop_playback")]
        for e in self.state.edges:
            if e.kind == "dtmf" and digit in e.values:
                return [Action("stop_playback")] + self._follow(e)
        return self._invalid()

    def _ask_done(self) -> list[Action]:
        assert self.state is not None and self._ask is not None
        self.vars[self._ask["var"]] = self._digits
        self._digits, self._ask = "", None
        e = self.state.edge("ok")
        return self._follow(e) if e else self._invalid()

    def _on_speech(self, text: str) -> list[Action]:
        assert self.state is not None
        text = (text or "").strip()
        if not text:
            return self._on_timeout()
        out = self.nlu(text, self.today)
        it, intent = out.interpretation, out.intent
        self.vars["last_utterance"] = text
        self.vars["last_intent"] = intent.intent
        self.vars["last_intent_confidence"] = intent.confidence
        if intent.entities.specialty:
            self.vars.setdefault("specialty", intent.entities.specialty)
            self.vars["needs_referral"] = intent.entities.needs_referral
        if intent.entities.doctor_surname:
            self.vars["doctor_surname"] = intent.entities.doctor_surname
        if intent.entities.for_other is not None:
            self.vars.setdefault("for_other", intent.entities.for_other)
        # remember any date / time / day part the caller volunteered ("к кардиологу в пятницу утром")
        if it.date is not None:
            self.vars["said_date"] = it.date.isoformat()
        if it.time is not None:
            self.vars["said_time"] = it.time.strftime("%H:%M")
        if it.daypart is not None:
            self.vars["said_daypart"] = it.daypart
            self.vars["said_daypart_spoken"] = DAYPART_SPOKEN[it.daypart]
        for e in self.state.edges:
            k = e.kind
            if k == "yes" and it.yes_no is True:
                return self._follow(e)
            if k == "no" and it.yes_no is False:
                return self._follow(e)
            if k == "date" and it.date is not None:
                return self._follow(e)
            if k == "time" and it.time is not None:
                return self._follow(e)
            if k == "daypart" and it.daypart is not None:
                return self._follow(e)
            if k == "digits" and len(it.digits) >= 2:
                self.vars["said_digits"] = it.digits
                return self._follow(e)
            if k == "intent" and intent.intent in e.values and intent.confidence >= self.intent_threshold:
                return self._follow(e)
            if k == "any":
                return self._follow(e)
        return self._invalid()

    def _on_timeout(self) -> list[Action]:
        assert self.state is not None
        if self._ask is not None and len(self._digits) >= int(self._ask["min"]):
            return self._ask_done()
        self._digits = ""
        self.retries[self.state.name] = self.retries.get(self.state.name, 0) + 1
        r = self.state.edge("retry")
        if r is not None and r.count is not None and self.retries[self.state.name] >= r.count:
            return self._follow(r)
        e = self.state.edge("timeout")
        if e is not None:
            return self._follow(e)
        return self._enter(self.state.name, self.state.name)

    def _invalid(self) -> list[Action]:
        assert self.state is not None
        self._digits = ""
        self.retries[self.state.name] = self.retries.get(self.state.name, 0) + 1
        r = self.state.edge("retry")
        if r is not None and r.count is not None and self.retries[self.state.name] >= r.count:
            return [Action("stop_playback")] + self._follow(r)
        e = self.state.edge("invalid")
        if e is not None:
            return [Action("stop_playback")] + self._follow(e)
        return [Action("stop_playback")] + self._enter(self.state.name, self.state.name)

    def _on_module(self, event: Event) -> list[Action]:
        assert self.state is not None
        if self._pending is None or event.request_id not in (None, self._pending.request_id):
            self.warnings.append(f"stale module result {event.request_id} ignored")
            return []
        self._pending = None
        for k, v in (event.payload or {}).items():
            self.vars[k] = v
        self.vars["last_status"] = event.value
        e = self.state.edge(event.value) or self.state.edge("error")
        if e is None:
            self.finished, self.status = True, "error"
            return [Action("end", args={"status": "error"})]
        return self._follow(e)

    # ---- helpers ------------------------------------------------------------------

    def _follow(self, e: Edge) -> list[Action]:
        assert self.state is not None
        for k, v in e.sets.items():
            self.vars[k] = self._value(v)
            if k == "said_daypart" and self.vars[k] in DAYPART_SPOKEN:
                self.vars["said_daypart_spoken"] = DAYPART_SPOKEN[self.vars[k]]
        return self._enter(e.target, self.state.name)

    def _value(self, raw: str):
        if raw.startswith("$"):
            return self.vars.get(raw[1:])
        if raw in ("true", "false"):
            return raw == "true"
        return raw

    def _render(self, text: str) -> str:
        def sub(m: re.Match[str]) -> str:
            key = m.group(1)
            if key in self.vars and self.vars[key] is not None:
                return str(self.vars[key])
            self.warnings.append(f"unresolved placeholder {{{key}}} in {self.state_name}")
            return m.group(0)

        return _PLACEHOLDER_RE.sub(sub, text)
