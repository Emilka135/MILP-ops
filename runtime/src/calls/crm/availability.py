"""Request-scoped availability filters shared by deterministic registry operations."""
from contextlib import contextmanager
from contextvars import ContextVar
import re

_CONSTRAINTS = ContextVar("clinic_availability_constraints", default=None)


def current():
    return _CONSTRAINTS.get() or {}


@contextmanager
def request_constraints(spec):
    from clinic.availability_constraints import validate
    token = _CONSTRAINTS.set(validate(spec))
    try:
        yield
    finally:
        _CONSTRAINTS.reset(token)


def positional_filter():
    from clinic.availability_constraints import sql_filter
    clause, named = sql_filter(current())
    values = []

    def bind(match):
        values.append(named[match.group()[1:]])
        return "?"

    # The clause is generated by a fixed SQL helper. Values stay bound params.
    return re.sub(r":[A-Za-z_][A-Za-z_0-9]*", bind, clause), values
