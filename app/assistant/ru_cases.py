"""Падежи для названий специальностей и штатных формулировок.

Регламент требует живого, а не канцелярского языка; фразы вида «запись к
терапевт» недопустимы. Здесь — минимально нужные формы: дательный («к кому»)
и винительный («на кого / к кому» совпадает с дательным для одушевлённых).
"""

from __future__ import annotations

# Специальные формы: у составных и заимствованных названий правило не работает
DATIVE_IRREGULAR = {
    "акушер-гинеколог": "акушеру-гинекологу",
    "травматолог-ортопед": "травматологу-ортопеду",
    "врач общей практики": "врачу общей практики",
    "оториноларинголог": "оториноларингологу",
    "офтальмолог": "офтальмологу",
    "дерматовенеролог": "дерматовенерологу",
    "гастроэнтеролог": "гастроэнтерологу",
    "эндокринолог": "эндокринологу",
    "пульмонолог": "пульмонологу",
    "ревматолог": "ревматологу",
    "инфекционист": "инфекционисту",
    "терапевт": "терапевту",
    "педиатр": "педиатру",
    "хирург": "хирургу",
    "невролог": "неврологу",
    "кардиолог": "кардиологу",
    "уролог": "урологу",
    "стоматолог": "стоматологу",
    "психиатр": "психиатру",
    "онколог": "онкологу",
    "нефролог": "нефрологу",
    "гематолог": "гематологу",
    "аллерголог": "аллергологу",
}

GENITIVE_IRREGULAR = {
    "акушер-гинеколог": "акушера-гинеколога",
    "травматолог-ортопед": "травматолога-ортопеда",
    "врач общей практики": "врача общей практики",
}

# Кого приглашаем в SMS и ответах: краткая «человеческая» форма
PLAIN = {
    "оториноларинголог": "ЛОР",
    "акушер-гинеколог": "гинеколог",
    "травматолог-ортопед": "травматолог",
    "дерматовенеролог": "дерматолог",
}


def _by_rule(word: str, *, dative: bool) -> str:
    """Правило для существительных мужского рода на согласный и -ь."""
    if word.endswith("ист"):
        return word + "у"
    if word.endswith("лог"):
        return word + "у"
    if word.endswith("атр"):
        return word.replace("атр", "атру")
    if word.endswith("ург"):
        return word + "у"
    if dative:
        return word + "у"
    return word + "а"


def dative(specialty: str) -> str:
    """«к терапевту», «к оториноларингологу»."""
    if not specialty:
        return "врачу"
    key = specialty.strip().lower()
    if key in DATIVE_IRREGULAR:
        return DATIVE_IRREGULAR[key]
    if "-" in key:
        return "-".join(dative(part) for part in key.split("-"))
    return _by_rule(key, dative=True)


def genitive(specialty: str) -> str:
    """«запись к терапевту» → «отмена записи к терапевту» требует «терапевта»."""
    if not specialty:
        return "врача"
    key = specialty.strip().lower()
    if key in GENITIVE_IRREGULAR:
        return GENITIVE_IRREGULAR[key]
    if "-" in key:
        return "-".join(genitive(part) for part in key.split("-"))
    return _by_rule(key, dative=False)


def short(specialty: str) -> str:
    """«ЛОР» вместо «оториноларинголог» в разговорной реплике."""
    return PLAIN.get((specialty or "").strip().lower(), specialty)


__all__ = ["dative", "genitive", "short", "DATIVE_IRREGULAR", "GENITIVE_IRREGULAR", "PLAIN"]
